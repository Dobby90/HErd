import { expect, it } from 'vitest';
import { SqlService } from '@erd/sql-service';
import { createSqlRegistry } from '../apps/api/src/sql-registry.js';
import { exportDocument, exportTarget } from '../packages/test-fixtures/src/ddl-export.js';

const service = new SqlService(createSqlRegistry());
const parse = (sql: string, defaultNamespace = 'public') => service.parse({ sql, defaultNamespace, target: exportTarget });

it('imports conditional CREATE TABLE DDL and skips existing tables and their comments on append', async () => {
  const sql = `
CREATE TABLE IF NOT EXISTS xaiops.xaiops_config_network (
  network_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  target_id VARCHAR(255) NOT NULL,
  "desc" VARCHAR(1000),
  enable BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT xaiops_config_network_pk PRIMARY KEY (network_id),
  CONSTRAINT xaiops_config_network_target_id_uk UNIQUE (target_id)
);
COMMENT ON TABLE xaiops.xaiops_config_network IS '시스템-네트워크(meta)';
COMMENT ON COLUMN xaiops.xaiops_config_network."desc" IS '장비 설명';`;
  const original = await parse(sql, 'xaiops');
  if (original.status !== 'parsed') throw new Error(JSON.stringify(original.diagnostics));
  expect(original.losses).toEqual([]);
  expect(original.catalog.tables).toMatchObject([{ physicalName: 'xaiops_config_network', description: '시스템-네트워크(meta)' }]);
  expect(original.catalog.columns).toEqual(expect.arrayContaining([
    expect.objectContaining({ physicalName: 'network_id', identity: 'by-default' }),
    expect.objectContaining({ physicalName: 'desc', description: '장비 설명' }),
    expect.objectContaining({ physicalName: 'enable', nullable: false, default: expect.objectContaining({ sql: 'TRUE' }) }),
  ]));
  expect(original.catalog.constraints.map(key => key.kind)).toEqual(['pk', 'unique']);
  const baseCatalog = original.catalog;
  const originalSnapshot = structuredClone(baseCatalog);
  const append = (sql: string) => service.parse({ sql, defaultNamespace: 'public', target: exportTarget, baseCatalog });
  const retry = await append(sql.replace('장비 설명', '새 설명'));
  expect(retry).toMatchObject({ status: 'blocked', diagnostics: [
    { code: 'existing-table-skipped', severity: 'info' }, { code: 'no-new-tables' },
  ] });
  expect(retry).not.toHaveProperty('catalog');

  const mixed = await append(sql + `
COMMENT ON COLUMN xaiops.xaiops_config_network.not_in_existing_model IS '가져오기 대상 설명';
CREATE TABLE IF NOT EXISTS public.xaiops_config_network (network_id integer REFERENCES xaiops.xaiops_config_network(network_id));`);
  if (mixed.status !== 'parsed') throw new Error(JSON.stringify(mixed.diagnostics));
  expect(mixed.statements.map(item => item.status)).toEqual([
    'skipped-existing', 'skipped-existing', 'skipped-existing', 'skipped-existing', 'converted',
  ]);
  expect(mixed.losses).toEqual([]);
  expect(mixed.catalog.tables).toMatchObject([{ physicalName: 'xaiops_config_network', namespaceId: mixed.catalog.namespaces[0].id }]);
  expect(mixed.catalog.namespaces).toMatchObject([{ physicalName: 'public' }]);
  expect(mixed.catalog.constraints).toMatchObject([{ kind: 'fk', targetTableId: baseCatalog.tables[0].id }]);
  expect(baseCatalog).toEqual(originalSnapshot);
});

it('parses all stage 4 statements, preserves dependencies, and re-exports an equivalent catalog', async () => {
  const original = exportDocument();
  for (const tableIds of [undefined, ['a']]) {
    const exported = await service.generate({ document: original, target: exportTarget, tableIds });
    if (exported.status !== 'generated') throw new Error(JSON.stringify(exported.diagnostics));
    const result = await parse(exported.sql);
    if (result.status !== 'parsed') throw new Error(JSON.stringify(result.diagnostics));
    expect(result.losses).toEqual([]);
    expect(result.catalog.tables.map(item => item.physicalName).sort()).toEqual(tableIds ? ['select', 'select'] : ['select', 'select', 'unused']);
    const again = await service.generate({ document: { ...original, catalog: result.catalog, views: [] }, target: exportTarget });
    if (again.status !== 'generated') throw new Error(JSON.stringify(again.diagnostics));
    const canonical = (sql: string) => sql.split('\n\n').sort();
    // PostgreSQL writes the implicit NO ACTION clauses on import.
    expect(canonical(again.sql)).toEqual(canonical(exported.sql));
  }
});

it('resolves fixed search paths and distinguishes serial ownership from explicit IDENTITY options', async () => {
  const result = await parse(`CREATE SCHEMA "업무"; CREATE SCHEMA twin;
SET search_path TO "업무", public;
CREATE TABLE Child (id bigserial PRIMARY KEY, link integer REFERENCES twin.Parent (id));
CREATE TABLE twin.Parent (id integer PRIMARY KEY, seq integer);
ALTER TABLE twin.Parent ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME twin.custom START WITH 9 INCREMENT BY 3);
ALTER TABLE twin.Parent ALTER COLUMN seq SET GENERATED ALWAYS;
CREATE TABLE twin.Child (n bigint);
CREATE UNIQUE INDEX child_unique_index ON twin.Child (n);
ALTER TABLE twin.Child ADD CONSTRAINT child_unique UNIQUE USING INDEX child_unique_index;`);
  if (result.status !== 'parsed') throw new Error(JSON.stringify(result.diagnostics));
  expect(result.losses).toEqual([]);
  const { tables, columns, sequences, constraints } = result.catalog;
  expect(tables.filter(item => item.physicalName === 'child')).toHaveLength(2);
  const serial = columns.find(column => column.default?.sql.includes('nextval'))!;
  expect(serial.type.reference).toEqual({ kind: 'native', name: 'bigint' });
  expect(serial.nullable).toBe(false);
  expect(sequences).toEqual([expect.objectContaining({ physicalName: 'child_id_seq', dataType: 'bigint', ownedByColumnId: serial.id })]);
  expect(serial.default?.references).toEqual([sequences[0].id]);
  const identity = columns.find(column => column.physicalName === 'seq')!;
  expect(identity).toMatchObject({ identity: 'always', identitySequence: { physicalName: 'custom', start: '9', increment: '3' }, nullable: false });
  expect(result.catalog.indexes).toEqual([]);
  expect(constraints).toEqual(expect.arrayContaining([expect.objectContaining({ kind: 'unique', physicalName: 'child_unique' })]));
  expect(constraints.find(key => key.kind === 'fk')).toMatchObject({ targetTableId: tables.find(table => table.physicalName === 'parent')?.id });
});

it('distinguishes loss, control statements, syntax positions, contradictory definitions and unresolved dependencies', async () => {
  const source = `\uFEFF-- first; line
\\restrict Abc123
/* outer; /* inner */ */
CREATE TABLE "한글" (value text DEFAULT $tag$O'Brien;\\i literal
next$tag$, other text DEFAULT E'quote\\' and ;');
CREATE VIEW excluded AS SELECT * FROM "한글";
\\unrestrict Abc123
`;
  const parsed = await parse(source);
  if (parsed.status !== 'parsed') throw new Error(JSON.stringify(parsed.diagnostics));
  expect(parsed.statements.map(item => item.status)).toEqual(['ignored-nonstructural', 'converted', 'unsupported', 'ignored-nonstructural']);
  expect(parsed.losses[0].location).toMatchObject({ line: 6, column: 1, offset: source.indexOf('CREATE VIEW') });
  expect(parsed.catalog.columns[0].default?.sql).toContain("O''Brien;");
  const bad = source.replace('CREATE VIEW', 'CREAT VIEW');
  const result = await parse(bad);
  expect(result).toMatchObject({ status: 'blocked', diagnostics: [{ code: 'postgresql-syntax-error',
    location: { line: 6, column: 1, offset: bad.indexOf('CREAT VIEW') } }] });
  const commands = await parse('CREATE TABLE allowed (id integer);\n  \\include file.sql\n');
  expect(commands).toMatchObject({ status: 'blocked', diagnostics: [{ code: 'blocked-psql-command', location: { line: 2, column: 3 } }] });
  const cases = [
    'CREATE TABLE duplicate (id integer); CREATE TABLE duplicate (id integer);',
    'CREATE TABLE ref (id integer REFERENCES omitted (id)); CREATE VIEW omitted AS SELECT 1 AS id;',
    'CREATE EXTENSION hstore; CREATE TABLE ext (data hstore);',
    'CREATE EXTENSION other; CREATE TABLE ext (val integer DEFAULT other_function());',
    'SET search_path TO "$user", public; CREATE TABLE example (id integer);',
    'CREATE TABLE missing (id integer); CREATE TABLE refs (id integer REFERENCES missing (id)); CREATE UNIQUE INDEX p ON missing (id) WHERE id > 0;',
    'SET search_path TO pg_catalog; CREATE TABLE example (id integer);',
    "CREATE FUNCTION public.lower(text) RETURNS text LANGUAGE sql AS $$SELECT 'different'$$; CREATE TABLE t (v text DEFAULT lower('X'));",
    'CREATE DOMAIN public.text AS integer; SET search_path TO public, pg_catalog; CREATE TABLE t (v "text");',
    'CREATE TABLE test (id integer); COPY test FROM STDIN;',
  ];
  for (const sql of cases) {
    const result = await parse(sql);
    expect(result, sql).toMatchObject({ status: 'blocked', diagnostics: expect.arrayContaining([expect.objectContaining({ severity: 'error' })]) });
    expect(result).not.toHaveProperty('catalog');
  }
  expect(await parse('PGDMPraw')).toMatchObject({ status: 'blocked', diagnostics: [{ code: 'unsupported-sql-file' }] });
});
